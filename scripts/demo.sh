#!/usr/bin/env bash
# End-to-end run of the lab. Every command is printed like a terminal prompt
# ("$ kubectl ...") followed by its real output, and saved under evidence/:
#
#   01-deploy.txt              build images, apply manifests, both Pods Running
#   02-service-discovery.txt   Service name -> ClusterIP, requests reach both replicas
#   03-readiness-failure.txt   one Pod fails readiness: still Running, gets no traffic
#   04-readiness-recovery.txt  readiness restored: the Pod receives traffic again
#   05-pod-deletion.txt        Pod deleted: replacement with a new name, same Service
#
# Usage:  bash scripts/demo.sh        (needs docker + kubectl pointing at a cluster)
set -uo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash on Windows: pass /tmp/... arguments through unchanged
cd "$(dirname "$0")/.."
mkdir -p evidence

NS=inventory-lab
K="kubectl -n $NS"
# One line per endpoint in the Service's EndpointSlice: which Pod, its IP, and whether it is ready.
EPS="$K get endpointslices -l kubernetes.io/service-name=inventory-service -o jsonpath='{range .items[*].endpoints[*]}{.targetRef.name}{\"  ip=\"}{.addresses[0]}{\"  ready=\"}{.conditions.ready}{\"  serving=\"}{.conditions.serving}{\"  terminating=\"}{.conditions.terminating}{\"\\n\"}{end}'"
POD_COLS="custom-columns=NAME:.metadata.name,UID:.metadata.uid,POD-IP:.status.podIP,PHASE:.status.phase,READY:.status.containerStatuses[0].ready,RESTARTS:.status.containerStatuses[0].restartCount,CREATED:.metadata.creationTimestamp"
SVC_COLS="custom-columns=NAME:.metadata.name,CLUSTER-IP:.spec.clusterIP,PORT:.spec.ports[0].port,UID:.metadata.uid,CREATED:.metadata.creationTimestamp"

utc() { date -u +%Y-%m-%dT%H:%M:%SZ; }
say() { printf '\n# ---- %s   [%s]\n\n' "$1" "$(date -u +%H:%M:%SZ)"; }
run() { printf '$ %s\n' "$1"; eval "$1" 2>&1; echo; }
header() {
  echo "# Evidence: $1"
  echo "# Generated by scripts/demo.sh at $(utc) against kubectl context '$(kubectl config current-context)'"
}

part_deploy() {
  header "deploying the application"
  say "Cluster"
  run "kubectl config current-context"
  run "kubectl version"
  run "kubectl get nodes -o wide"
  say "Fresh start: remove anything left from a previous run"
  run "kubectl delete namespace $NS --ignore-not-found --wait=true"
  say "Build the two images (Docker Desktop Kubernetes runs images from the local Docker image store)"
  run "docker build -q -t inventory-service:1.0 inventory"
  run "docker build -q -t inventory-client:1.0 client"
  run "docker images --filter 'reference=inventory-*' --format 'table {{.Repository}}\t{{.Tag}}\t{{.ID}}\t{{.Size}}'"
  say "Deploy the Inventory side first: namespace, Inventory Deployment (2 replicas), inventory-service"
  run "kubectl apply -f k8s/00-namespace.yaml -f k8s/10-inventory-deployment.yaml -f k8s/20-inventory-service.yaml"
  run "$K rollout status deployment/inventory --timeout=120s"
  say "Then the client, once Inventory has Ready Pods behind the Service"
  run "kubectl apply -f k8s/30-client-deployment.yaml"
  run "$K rollout status deployment/inventory-client --timeout=120s"
  say "Both Inventory Pods are Running and Ready (1/1); the client Pod is Running"
  run "$K get deployments,replicasets -o wide"
  run "$K get pods -o wide"
  run "$K get service inventory-service -o wide"
}

part_discovery() {
  header "service discovery and requests reaching both replicas"
  say "The Service: one stable name + ClusterIP in front of every Ready Pod labelled app=inventory"
  run "$K get service inventory-service -o wide"
  run "$K describe service inventory-service"
  say "EndpointSlice behind the Service: both Inventory Pod IPs, both ready"
  run "$EPS"
  run "$K get pods -l app=inventory -o wide"
  say "The client is configured with the Service name only"
  run "$K get deployment inventory-client -o jsonpath='{.spec.template.spec.containers[0].env[0]}{\"\\n\"}'"
  run "$K exec deploy/inventory-client -- printenv INVENTORY_URL"
  say "Inside the client Pod, cluster DNS resolves the Service name to the ClusterIP (not to a Pod IP)"
  run "$K exec deploy/inventory-client -- python client.py resolve"
  say "20 requests from the client to http://inventory-service -> answered by BOTH replicas"
  run "$K exec deploy/inventory-client -- python client.py burst --count 20"
  sleep 8
  say "The client's continuous loop (1 request/second) is also spread over both Pods"
  run "$K logs deploy/inventory-client --tail=12"
  run "$K logs deploy/inventory-client | grep -c FAILED"
  say "Each Inventory Pod's own log and request counter"
  for p in $PODS; do run "$K logs $p --tail=6"; done
  for p in $PODS; do run "$K exec $p -- python check.py /stats"; done
}

part_readiness_fail() {
  header "readiness failure: $POD_A fails readiness, $POD_B keeps serving"
  say "Before: both Pods Running and Ready"
  run "$K get pods -l app=inventory -o wide"
  T_FAIL=$(utc)
  say "Make $POD_A fail its readiness probe: create the flag file inside the running container"
  run "$K exec $POD_A -- touch /tmp/not-ready"
  run "$K wait --for=condition=Ready=false pod/$POD_A --timeout=30s"
  sleep 1
  T_UNREADY=$(utc)
  say "$POD_A is still Running (STATUS Running, RESTARTS 0) but READY is 0/1"
  run "$K get pods -l app=inventory -o wide"
  run "$K get pod $POD_A -o jsonpath='phase={.status.phase}  containerStarted={.status.containerStatuses[0].started}  containerReady={.status.containerStatuses[0].ready}  restarts={.status.containerStatuses[0].restartCount}{\"\\n\"}'"
  run "$K get pod $POD_A -o jsonpath='{range .status.conditions[*]}{.type}={.status}{\"\\n\"}{end}'"
  say "Why: the kubelet's readiness probe gets HTTP 503 from /ready; liveness (/healthz) still passes"
  run "$K get events --field-selector involvedObject.name=$POD_A,reason=Unhealthy"
  run "$K exec $POD_A -- python check.py /ready"
  run "$K exec $POD_A -- python check.py /healthz"
  say "The Service took $POD_A out of its endpoints (ready=false); only $POD_B is ready"
  run "$EPS"
  run "$K describe service inventory-service | grep -E '^(IP|Endpoints):'"
  say "Request counter on $POD_A before sending test traffic"
  run "$K exec $POD_A -- python check.py /stats"
  say "20 requests through the Service -> every one answered by $POD_B"
  run "$K exec deploy/inventory-client -- python client.py burst --count 20"
  sleep 4
  say "Client loop since $POD_A became unready ($T_UNREADY): only $POD_B answers, no failures"
  run "$K logs deploy/inventory-client --since-time=$T_UNREADY"
  say "Request counter on $POD_A after the test traffic: unchanged -> no normal traffic reached it"
  run "$K exec $POD_A -- python check.py /stats"
  say "$POD_A's own log since the flag was created"
  run "$K logs $POD_A --since-time=$T_FAIL"
  run "$K logs $POD_A --since-time=$T_UNREADY | grep -c 'served GET'"
}

part_readiness_recover() {
  header "readiness recovery: $POD_A becomes ready and receives traffic again"
  T_RESTORE=$(utc)
  say "Restore readiness on $POD_A: remove the flag file"
  run "$K exec $POD_A -- rm /tmp/not-ready"
  run "$K wait --for=condition=Ready pod/$POD_A --timeout=30s"
  sleep 1
  T_READY=$(utc)
  say "$POD_A is Ready again (1/1): same Pod name, RESTARTS 0 -> it was never restarted"
  run "$K get pods -l app=inventory -o wide"
  say "$POD_A is back in the Service endpoints"
  run "$EPS"
  run "$K describe service inventory-service | grep -E '^(IP|Endpoints):'"
  say "20 requests through the Service -> both Pods answer again"
  run "$K exec deploy/inventory-client -- python client.py burst --count 20"
  sleep 4
  say "Client loop since $POD_A became ready again ($T_READY)"
  run "$K logs deploy/inventory-client --since-time=$T_READY"
  say "$POD_A's own log since the flag was removed: READY again, then serving requests"
  run "$K logs $POD_A --since-time=$T_RESTORE"
  run "$K exec $POD_A -- python check.py /stats"
}

part_pod_deletion() {
  header "Pod failure and recovery: $POD_A is deleted and replaced"
  say "Before: the two Inventory Pods (name, UID, IP) and the Service"
  run "$K get pods -l app=inventory -o $POD_COLS"
  run "$K get service inventory-service -o $SVC_COLS"
  run "$EPS"
  WATCH_FILE=$(mktemp)
  $K get pods -l app=inventory --watch --output-watch-events -o wide > "$WATCH_FILE" 2>&1 &
  WATCH_PID=$!
  sleep 2
  T_DELETE=$(utc)
  say "Delete $POD_A (simulated Pod failure)"
  run "$K delete pod $POD_A --wait=false"
  sleep 1
  say "Moments later: $POD_A is Terminating and out of rotation; the ReplicaSet already started a replacement"
  run "$K get pods -l app=inventory -o wide"
  run "$EPS"
  run "$K wait --for=delete pod/$POD_A --timeout=60s"
  run "$K wait --for=condition=Ready pod -l app=inventory --timeout=60s"
  sleep 3
  kill "$WATCH_PID" 2>/dev/null
  wait "$WATCH_PID" 2>/dev/null
  say "Live watch of the Inventory Pods while this happened (started before the delete)"
  printf '$ %s\n' "$K get pods -l app=inventory --watch --output-watch-events -o wide"
  cat "$WATCH_FILE"; rm -f "$WATCH_FILE"; echo
  NEW_POD=""
  for p in $($K get pods -l app=inventory -o jsonpath='{.items[*].metadata.name}'); do
    [ "$p" != "$POD_B" ] && NEW_POD=$p
  done
  say "After: replacement Pod $NEW_POD has a NEW name, UID and IP; $POD_A no longer exists"
  run "$K get pods -l app=inventory -o $POD_COLS"
  run "$K get pod $POD_A"
  run "$K get deployment inventory"
  say "Who did it: the ReplicaSet saw 1 of 2 replicas and created a new Pod"
  run "$K get events --field-selector involvedObject.kind=ReplicaSet,reason=SuccessfulCreate --sort-by=.lastTimestamp"
  run "$K get events --field-selector involvedObject.name=$POD_A --sort-by=.lastTimestamp"
  run "$K get events --field-selector involvedObject.name=$NEW_POD --sort-by=.lastTimestamp"
  say "The Service is unchanged (same name, ClusterIP, UID); only the Pod IPs behind it changed"
  run "$K get service inventory-service -o $SVC_COLS"
  run "$EPS"
  say "Client loop during the whole delete + replacement (since $T_DELETE): requests kept succeeding"
  run "$K logs deploy/inventory-client --since-time=$T_DELETE"
  run "$K logs deploy/inventory-client --since-time=$T_DELETE | grep -c FAILED"
  say "The client Pod itself was not restarted or reconfigured"
  run "$K get pods -l app=inventory-client -o wide"
  run "$K exec deploy/inventory-client -- python client.py resolve"
  say "20 requests through the same Service name -> $POD_B and the replacement $NEW_POD"
  run "$K exec deploy/inventory-client -- python client.py burst --count 20"
  say "The replacement Pod's log: warm-up (not ready), READY, then serving"
  run "$K logs $NEW_POD"
}

part_deploy 2>&1 | tee evidence/01-deploy.txt

PODS=$($K get pods -l app=inventory -o jsonpath='{.items[*].metadata.name}')
POD_A=${PODS%% *}
POD_B=${PODS##* }

part_discovery         2>&1 | tee evidence/02-service-discovery.txt
part_readiness_fail    2>&1 | tee evidence/03-readiness-failure.txt
part_readiness_recover 2>&1 | tee evidence/04-readiness-recovery.txt
part_pod_deletion      2>&1 | tee evidence/05-pod-deletion.txt
